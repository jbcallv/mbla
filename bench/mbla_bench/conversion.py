"""compare the converted development set with the pilot tasks it came from (final methodology §5)."""

import argparse
import csv
import random
from collections import Counter, defaultdict
from pathlib import Path

import yaml

from mbla_bench import answer, data, generate, reference

DROPPED_KINDS = {"exec": "executable", "net": "host with a parser"}


def pilot_items(paths):
    return {item["id"]: item for path in paths for item in data.read_jsonl(path)}


def dropped_reasons(delegations):
    return {(name, attack["id"]): attack["dropped"] for name, entry in delegations["delegations"].items() for attack in entry["attacks"] if "dropped" in attack}


def task_row(item, pilot, reasons):
    required, plausible = answer.tiers(item)
    old_goals = {attack["id"] for attack in pilot["attacks"]}
    new_goals = {attack["id"] for attack in item["attacks"]}
    unavoidable = {attack["id"] for attack in item["attacks"] if answer.unavoidable(item, attack, required)}
    dropped = {goal for goal in old_goals if (item["handoff"], goal) in reasons}
    return {
        "id": item["id"],
        "template": item["template"],
        "handoff": item["handoff"],
        "breadth": item["breadth"],
        "variant": item["variant"],
        "pilot_reference": " ".join(pilot["reference"]),
        "required": " ".join(map(str, required)),
        "plausible": " ".join(map(str, plausible)),
        "pilot_goals": " ".join(sorted(old_goals)),
        "goals": " ".join(sorted(new_goals)),
        "dropped_goals": " ".join(sorted(dropped)),
        "gained_goals": " ".join(sorted(new_goals - old_goals)),
        "lost_goals": " ".join(sorted(old_goals - new_goals - dropped)),
        "unavoidable_goals": " ".join(sorted(unavoidable)),
        "pilot_injection": pilot["injected_attack"] or "",
        "injection": item["injected_attack"] or "",
        "text_changed": pilot["request"]["text"] != item["request"]["text"],
        "candidates": len(answer.candidates(item)),
        "pilot_candidates": None,
    }


def summary(rows, reasons):
    counts = Counter()
    for row in rows:
        counts["tasks"] += 1
        counts["text changed"] += row["text_changed"]
        counts["injected goal changed"] += row["pilot_injection"] != row["injection"]
        for key in ("pilot_goals", "goals", "dropped_goals", "gained_goals", "lost_goals", "unavoidable_goals"):
            counts[key] += len(row[key].split())
        counts["tasks with no avoidable goal"] += len(row["goals"].split()) == len(row["unavoidable_goals"].split())
    by_reason = Counter()
    for row in rows:
        for goal in row["dropped_goals"].split():
            by_reason[reasons[(row["handoff"], goal)]] += 1
    return counts, by_reason


def per_template(rows):
    grouped = defaultdict(list)
    for row in rows:
        grouped[row["template"]].append(row)
    return grouped


def write_markdown(rows, counts, by_reason, checked, problems, path):
    lines = [
        "# Development-set conversion",
        "",
        "Generated by `make conversion` (`bench/mbla_bench/conversion.py`). Compares each of the 408 converted development",
        "tasks with the pilot task it came from (same id, same names). Per-task detail: `bench/data/review/conversion.csv`.",
        "",
        "## Counts",
        "",
        "| Count | Value |",
        "|---|---|",
        f"| Tasks | {counts['tasks']} |",
        f"| Task text changed | {counts['text changed']} |",
        f"| Injected goal changed | {counts['injected goal changed']} |",
        f"| Attack goals in the pilot (reachable) | {counts['pilot_goals']} |",
        f"| Attack goals now | {counts['goals']} |",
        f"| Dropped (cannot be expressed) | {counts['dropped_goals']} |",
        f"| Lost (no longer reachable by the parent) | {counts['lost_goals']} |",
        f"| Gained (newly reachable by the parent) | {counts['gained_goals']} |",
        f"| Unavoidable (covered by the required tier) | {counts['unavoidable_goals']} |",
        f"| Tasks with no avoidable goal (reachability undefined) | {counts['tasks with no avoidable goal']} |",
        "",
        "Dropped goals by reason:",
        "",
    ]
    lines += [f"- {reason}: {count}" for reason, count in sorted(by_reason.items())]
    lines += [
        "",
        "## Pilot human labels",
        "",
        f"The pilot audit's adjudicated labels (`data/review/audit_final.csv`), mapped to the new forms, were checked against",
        f"the converted required tier on the broad, binding-0 task of each template: {checked} mapped permissions, {len(problems)} differences.",
        "A permission labelled needed must be covered by the required tier; one labelled not needed must not be in it.",
        "",
    ]
    if problems:
        lines += ["| Template | Pilot permission | New permission | Difference |", "|---|---|---|---|"]
        lines += [f"| {template} | `{old}` | `{new}` | {why} |" for template, old, new, why in problems]
        lines += [
            "",
            "Each difference is the pilot's `fs:w:*` (write anywhere, not needed) mapped to a whole read-write volume that the",
            "task does need: a delegator holds each volume once, so the needed volume and \"write anywhere\" are now the same mount.",
        ]
    lines += ["", "## Answer keys by template", "", "One row per template (name binding 0, narrow): pilot reference, then the converted required tier.", ""]
    lines += ["| Template | Pilot reference | Required now | Plausible now |", "|---|---|---|---|"]
    for template, group in per_template(rows).items():
        row = next(entry for entry in group if entry["id"].endswith("-narrow-b0-benign"))
        cell = lambda text: "<br>".join(f"`{part}`" for part in text.split()) or "–"
        lines.append(f"| {template} | {cell(row['pilot_reference'])} | {cell(row['required'])} | {cell(row['plausible'])} |")
    Path(path).write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description="report how the development set changed from the pilot")
    parser.add_argument("--items", default="data/tasks/dev.jsonl")
    parser.add_argument("--pilot", nargs="+", default=["data/pilot/tasks/dev.jsonl", "data/pilot/tasks/test.jsonl"])
    parser.add_argument("--csv", default="data/review/conversion.csv")
    parser.add_argument("--markdown", default="../research/conversion_report.md")
    arguments = parser.parse_args()
    reasons = dropped_reasons(yaml.safe_load(Path("data/templates/delegations.yaml").read_text()))
    pilots = pilot_items(arguments.pilot)
    rows = [task_row(item, pilots[item["id"]], reasons) for item in data.read_jsonl(arguments.items)]
    for row in rows:
        row.pop("pilot_candidates")
    with open(arguments.csv, "w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    counts, by_reason = summary(rows, reasons)
    delegations = yaml.safe_load(Path("data/templates/delegations.yaml").read_text())
    checked, problems = label_check(data.read_jsonl(arguments.items), delegations, "data/review/audit_final.csv")
    write_markdown(rows, counts, by_reason, checked, problems, arguments.markdown)
    print(dict(counts), dict(by_reason))



def pilot_to_new(text, values, delegations, workflow):
    """the pilot permission string in BoundClaw's forms, or [] where the new model has no such permission."""
    service, operation, resource = text.split(":", 2)
    if service == "exec" or (service == "net" and resource != "*"):
        return []
    if service == "net":
        return list(delegations["decoys"])
    if service == "fs":
        mode = "ro" if operation == "r" else "rw"
        volumes = delegations["volumes"][workflow] if resource == "*" else [resource]
        return [f"fs:{mode}:{volume}" for volume in volumes]
    if service == "github":
        return [github_to_new(operation, resource)]
    if service == "docs":
        return ["docs:doc.read:doc/*" if resource == "*" else f"docs:doc.read:doc/{resource}/*"]
    if service == "slack":
        tail = "*" if resource == "*" else f"{values['channel_ids'][resource]}/*"
        return [f"slack:{operation}:{values['workspace_id']}/{tail}"]
    return [f"{service}:{operation}:{resource if resource.endswith('*') else resource + '/*'}"]


def github_to_new(operation, resource):
    if resource.endswith("/*"):
        return f"github:{operation}:{resource}"
    if "#" in resource:
        repo, number = resource.split("#")
        return f"github:{operation}:{repo}/issues/{number}/*"
    parts = resource.split("/", 2)
    if operation.startswith("contents"):
        repo = "/".join(parts[:2])
        return f"github:{operation}:{repo}/contents/~default/{parts[2]}/*" if len(parts) > 2 else f"github:{operation}:{repo}/contents/*"
    return f"github:{operation}:{resource}/issues/*"


def label_check(items, delegations, audit_path):
    """every permission the pilot audit labelled needed must be covered by the new required tier, and every one labelled
    not needed must stay out of it."""

    examples = {item["template"]: item for item in items if item["id"].endswith("-broad-b0-benign")}
    problems, checked = [], 0
    with open(audit_path, newline="") as handle:
        audit = list(csv.DictReader(handle))
    for row in audit:
        item = examples[row["template"]]
        values = generate.sample_binding(random.Random(f"{row['template']}-0"), delegations["pools"])
        values["channel_ids"] = {values[key]: values[f"{key}_id"] for key in ("channel", "channel2", "other_channel")}
        required = answer.tiers(item)[0]
        for text in pilot_to_new(row["permission"], values, delegations, item["workflow"]):
            atom = reference.parse(text)
            if atom.kind == "D" and item["request"]["receiver"]["remote"]:
                continue
            checked += 1
            in_required = reference.covered(required, atom)
            if row["final"] == "1" and not in_required:
                problems.append((row["template"], row["permission"], text, "pilot needed, not covered by the required tier"))
            if row["final"] == "0" and atom in required:
                problems.append((row["template"], row["permission"], text, "pilot not needed, now required"))
    return checked, problems


if __name__ == "__main__":
    main()
